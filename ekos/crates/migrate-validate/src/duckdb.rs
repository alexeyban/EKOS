//! RFC 0259 D3 — DuckDB's canonical form (RFC 0155), so reconciliation and tiers V1–V3 can compare
//! a DuckDB gold mart with Trino silver.
//!
//! An in-tree [`CanonDialect`] passed as `Dialect::Registered(&DUCKDB)`: the RFC 0255 seam, with no
//! change to the [`crate::Dialect`] enum. Every expression uses DuckDB core functions only — no
//! `icu` extension, so a timestamp with a zone is rendered through `epoch_us` rather than `AT TIME
//! ZONE`, and the session's `TimeZone` setting never changes the canonical form.
//!
//! Proven by the conformance kit ([`crate::conformance::run`]) against DuckDB 1.5.5: through the
//! CLI in `tests/conformance.rs` (`EKOS_DUCKDB_CLI`) and in process in `ekos-plugin-duckdb`
//! (feature `duckdb`). The literals the kit renders are [`DuckDbLiterals`], hand-written.

use crate::conformance::{BUCKET_ROWS, Literals};
use crate::dialect::{CanonDialect, ColumnRule, Dialect};

/// DuckDB's canonical-form rules.
pub struct DuckDbCanon;

/// The one instance: `Dialect::Registered(&DUCKDB)`.
pub static DUCKDB: DuckDbCanon = DuckDbCanon;

/// The dialect value for DuckDB.
pub fn dialect() -> Dialect {
    Dialect::Registered(&DUCKDB)
}

/// The timestamp format of the canonical form: ISO 8601, `T`, six fraction digits, no offset.
const TS_FORMAT: &str = "'%Y-%m-%dT%H:%M:%S.%f'";

impl CanonDialect for DuckDbCanon {
    fn name(&self) -> &str {
        "duckdb"
    }

    fn canon_body(&self, expr: &str, rule: ColumnRule) -> String {
        let c = expr;
        match rule {
            // DuckDB string literals take a backslash literally, as PostgreSQL's do.
            ColumnRule::Text | ColumnRule::Char | ColumnRule::Inet => {
                format!("replace(replace(CAST({c} AS VARCHAR), '\\', '\\\\'), chr(31), '\\x1f')")
            }
            ColumnRule::Bool => format!("(CASE WHEN {c} THEN 't' ELSE 'f' END)"),
            ColumnRule::Int => format!("CAST({c} AS VARCHAR)"),
            // A DuckDB decimal renders at its own scale with a leading `0` and no exponent, and
            // `-0.00` is the integer 0 underneath, so rescaling first gives the fixed-scale form.
            ColumnRule::Decimal(s) => format!("CAST(CAST({c} AS DECIMAL(38, {s})) AS VARCHAR)"),
            // `epoch_us` of a `TIMESTAMPTZ` is UTC whatever the session's zone; `make_timestamp`
            // turns it back into a plain timestamp without consulting the zone.
            ColumnRule::TimestampUtc => {
                format!("strftime(make_timestamp(epoch_us({c})), {TS_FORMAT})")
            }
            ColumnRule::TimestampNaive => {
                format!("strftime(CAST({c} AS TIMESTAMP), {TS_FORMAT})")
            }
            ColumnRule::Date => format!("CAST(CAST({c} AS DATE) AS VARCHAR)"),
            // `CAST(time AS VARCHAR)` drops a zero fraction; a timestamp on the epoch day keeps it.
            ColumnRule::Time => {
                format!("strftime(DATE '1970-01-01' + CAST({c} AS TIME), '%H:%M:%S.%f')")
            }
            ColumnRule::Uuid => format!("lower(CAST({c} AS VARCHAR))"),
            ColumnRule::Bytes => format!("lower(hex({c}))"),
        }
    }

    /// `sha256` of a `VARCHAR` hashes its UTF-8 bytes and answers lowercase hex.
    fn hash_hex_expr(&self, text_expr: &str) -> String {
        format!("sha256({text_expr})")
    }

    /// DuckDB reads a `0x` string as hexadecimal, big-endian; 15 digits fit a `BIGINT`.
    fn prefix60_expr(&self, hash_expr: &str) -> String {
        format!("CAST(('0x' || substr({hash_expr}, 1, 15)) AS BIGINT)")
    }

    fn separator(&self) -> String {
        "chr(31)".into()
    }

    /// `octet_length` takes only `BLOB`/`BIT`; `strlen` counts a string's bytes.
    fn byte_length(&self, expr: &str) -> String {
        format!("strlen({expr})")
    }
}

/// DuckDB typed literals for the conformance kit, hand-written (never generated by the rules
/// under test).
pub struct DuckDbLiterals;

impl Literals for DuckDbLiterals {
    fn dialect(&self) -> Dialect {
        dialect()
    }

    fn literal(&self, case: &str) -> Option<String> {
        duckdb_literal(case).map(str::to_string)
    }

    fn unmapped(&self) -> Vec<(&'static str, &'static str)> {
        vec![
            (
                "interval_months_and_days",
                "Iceberg has no interval type, so a mart never holds one",
            ),
            (
                "array_with_null_element",
                "array rendering needs the type mapping",
            ),
            ("array_nested", "array rendering needs the type mapping"),
            (
                "array_empty",
                "an untyped empty array literal has no element type",
            ),
        ]
    }

    fn text(&self, text: &str) -> Option<String> {
        Some(format!("'{}'", text.replace('\'', "''")).replace('\u{1f}', "' || chr(31) || '"))
    }

    fn bucket_rows(&self) -> (String, &'static str, &'static str) {
        (
            format!(
                "(SELECT CAST(i AS BIGINT) AS id, CASE WHEN i % 7 = 0 THEN 'seven' ELSE 'other' \
                 END AS txt FROM range(1, {}) g(i)) t",
                BUCKET_ROWS + 1
            ),
            "id",
            "txt",
        )
    }
}

fn duckdb_literal(name: &str) -> Option<&'static str> {
    Some(match name {
        "null" => "CAST(NULL AS VARCHAR)",
        "empty_string" => "CAST('' AS VARCHAR)",
        // DuckDB literals take a backslash literally.
        "literal_backslash_n" => "CAST('\\N' AS VARCHAR)",
        "double_backslash" => "CAST('\\\\' AS VARCHAR)",
        "embedded_unit_separator" => "('a' || chr(31) || 'b')",
        "non_ascii" => "CAST('Ünïcödé' AS VARCHAR)",
        "emoji" => "CAST('🦀' AS VARCHAR)",
        "newline" => "('a' || chr(10) || 'b')",
        // A char(n) source lands in Iceberg, and so in a mart, as varchar with its padding.
        "char_trailing_spaces" => "CAST('ab   ' AS VARCHAR)",
        "bool_true" => "true",
        "bool_false" => "false",
        "int_zero" => "CAST(0 AS BIGINT)",
        "int_negative" => "CAST(-42 AS BIGINT)",
        "int_max" => "CAST(9223372036854775807 AS BIGINT)",
        "decimal_trailing_zeros" => "CAST('1.50' AS DECIMAL(18, 2))",
        "decimal_widened" => "CAST('1' AS DECIMAL(18, 0))",
        "decimal_leading_zero" => "CAST('0.05' AS DECIMAL(18, 2))",
        "decimal_negative" => "CAST('-1.50' AS DECIMAL(18, 2))",
        "decimal_negative_zero" => "CAST('-0.00' AS DECIMAL(18, 2))",
        "decimal_large" => "CAST('1234567890123456789012.34' AS DECIMAL(38, 2))",
        "timestamp_utc_whole_second" => "TIMESTAMPTZ '2026-09-24 12:30:00.000000+00:00'",
        "timestamp_utc_microseconds" => "TIMESTAMPTZ '2026-09-24 14:30:00.123456+02:00'",
        "timestamp_naive" => "TIMESTAMP '1999-12-31 23:59:59.999999'",
        "date_pre_1900" => "DATE '1850-06-15'",
        "date_epoch" => "DATE '1970-01-01'",
        "time_microseconds" => "TIME '01:02:03.000004'",
        "uuid_uppercase_input" => "UUID 'A0EEBC99-9C0B-4EF8-BB6D-6BB9BD380A11'",
        "bytes" => "from_hex('000FFF')",
        "bytes_empty" => "from_hex('')",
        // `inet` lands as varchar.
        "inet_v4" => "CAST('192.168.0.1/32' AS VARCHAR)",
        "inet_v6" => "CAST('2001:db8::1/128' AS VARCHAR)",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::conformance::coverage;
    use crate::dialect::{bucket_checksum_query, canon_expr, row_hash_expr};

    #[test]
    fn duckdb_is_a_registered_dialect() {
        let d = dialect();
        assert_eq!(d.name(), "duckdb");
        assert_eq!(d, Dialect::Registered(&DUCKDB));
        assert_ne!(d, Dialect::Trino);
        assert!(!d.digest_columns());
    }

    #[test]
    fn the_literal_table_is_complete() {
        assert!(
            coverage(&DuckDbLiterals).is_empty(),
            "{:?}",
            coverage(&DuckDbLiterals)
        );
        let mapped = crate::fixtures::cases()
            .iter()
            .filter(|(n, _, _)| DuckDbLiterals.literal(n).is_some())
            .count();
        assert_eq!(mapped, 31);
    }

    #[test]
    fn the_rules_render_in_duckdb_functions() {
        let d = dialect();
        assert_eq!(
            canon_expr(d, "c", ColumnRule::Decimal(2)),
            "(CASE WHEN \"c\" IS NULL THEN '\\N' ELSE CAST(CAST(\"c\" AS DECIMAL(38, 2)) AS VARCHAR) END)"
        );
        assert!(canon_expr(d, "ts", ColumnRule::TimestampUtc).contains("epoch_us(\"ts\")"));
        assert_eq!(
            row_hash_expr(d, &["a".into(), "b".into()]),
            "sha256(a || chr(31) || b)"
        );
        let q = bucket_checksum_query(d, "t", "pk", &["a".into()], 16);
        assert!(
            q.contains("MOD(CAST(('0x' || substr(sha256(pk), 1, 15)) AS BIGINT), 16) AS bucket"),
            "{q}"
        );
    }
}
