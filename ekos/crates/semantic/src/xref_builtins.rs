/// Qualifiers whose members are always built in.
const SYSTEM_QUALIFIERS: &[&str] = &["pg_catalog", "information_schema", "sys"];

/// `true` when `name` (normalized) is a function `dialect` provides.
pub(crate) fn is_builtin(name: &str, dialect: SqlDialect) -> bool {
    if let Some((q, _)) = name.rsplit_once('.') {
        let q = q.rsplit('.').next().unwrap_or(q);
        if SYSTEM_QUALIFIERS.contains(&q)
            || (dialect == SqlDialect::Oracle
                && (q.starts_with("dbms_") || q.starts_with("utl_") || q == "standard"))
        {
            return true;
        }
    }
    let tail = name.rsplit('.').next().unwrap_or(name);
    let has = |list: &[&str]| list.binary_search(&tail).is_ok();
    has(COMMON)
        || match dialect {
            SqlDialect::Postgres => has(POSTGRES) || tail.starts_with("pg_"),
            SqlDialect::Oracle => has(ORACLE),
        }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_and_lower_case() {
        for list in [COMMON, POSTGRES, ORACLE] {
            assert!(
                list.windows(2).all(|w| w[0] < w[1]),
                "unsorted or duplicate"
            );
            assert!(list.iter().all(|w| *w == w.to_lowercase()));
        }
    }

    #[test]
    fn built_ins_by_dialect_and_qualifier() {
        assert!(is_builtin("coalesce", SqlDialect::Oracle));
        assert!(is_builtin("nextval", SqlDialect::Postgres));
        assert!(!is_builtin("nextval", SqlDialect::Oracle));
        assert!(is_builtin("nvl", SqlDialect::Oracle));
        assert!(is_builtin("dbms_output.put_line", SqlDialect::Oracle));
        assert!(is_builtin("pg_catalog.format_type", SqlDialect::Postgres));
        assert!(!is_builtin("lsmb__next_businss_day", SqlDialect::Postgres));
    }
}
